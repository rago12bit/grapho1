"""The graph model, read from the graphs themselves: every label, every relationship type with the labels it joins,
the properties each carries, and how many there are. Writes docs/graph-model.md; a test regenerates it and fails if
the committed file has drifted from what the seed actually builds.

    docker compose run --rm -e FAULTLINE_GRAPH_PREFIX=schema_ -v "$PWD/docs:/app/docs" app python -m faultline.schema
"""
from __future__ import annotations

import sys
from pathlib import Path

from . import db, seed
from .db import Graph, client

DOC = Path(__file__).resolve().parents[1] / "docs" / "graph-model.md"
TENANTS = ("kestrel", "boutique")       # the synthetic company with every layer, and a real system


def read(g: Graph) -> dict:
    labels = {r["l"]: r["n"] for r in g.read("MATCH (n) UNWIND labels(n) AS l RETURN l, count(*) AS n")}
    props = {}
    for label in labels:
        rows = g.read(f"MATCH (n:`{label}`) UNWIND keys(n) AS k RETURN DISTINCT k ORDER BY k")
        props[label] = [r["k"] for r in rows]
    rels = g.read("""
        MATCH (a)-[r]->(b)
        RETURN labels(a)[0] AS a, type(r) AS t, labels(b)[0] AS b, count(*) AS n""")
    rprops = {}
    for t in sorted({r["t"] for r in rels}):
        rprops[t] = [r["k"] for r in g.read(f"MATCH ()-[r:`{t}`]->() UNWIND keys(r) AS k RETURN DISTINCT k ORDER BY k")]
    return {"labels": labels, "props": props, "rels": sorted(rels, key=lambda r: (r["t"], r["a"], r["b"])), "rprops": rprops}


def _agents_run(tenant: str) -> None:
    """What the agents write at run time: every open incident investigated (hypotheses, evidence, the CAUSED_BY
    chain, handoffs, proposed fixes proved on graph copies) and one conversation turn."""
    from . import agent, tools
    for inc in tools.list_incidents(Graph(tenant)):
        agent.investigate(tenant, inc["id"])
    agent.ask(tenant, "who owns payments-db", "schema-session-0001")


def render(models: dict[str, dict]) -> str:
    out = ["# Graph model", "",
           "Generated by `python -m faultline.schema` from freshly seeded graphs; `tests/test_schema.py` regenerates it",
           "and fails if this file has drifted. Counts are for the demo data. One FalkorDB graph per company.", ""]
    for tenant, m in models.items():
        seeded = m.get("seeded")
        mark = (lambda new: " ◆" if seeded is not None and new else "")
        out += [f"## {tenant}", "", f"{sum(m['labels'].values()):,} nodes, {sum(r['n'] for r in m['rels']):,} relationships, "
                f"{len(m['labels'])} labels, {len({r['t'] for r in m['rels']})} relationship types"
                + (" after the agents ran on every open incident. ◆ = written by the agents at run time, not by the seed."
                   if seeded is not None else ", as seeded."), "",
                "| label | nodes | properties |", "|---|---|---|"]
        for label in sorted(m["labels"]):
            new = seeded is not None and label not in seeded["labels"]
            out.append(f"| `{label}`{mark(new)} | {m['labels'][label]:,} | {', '.join(f'`{p}`' for p in m['props'][label])} |")
        out += ["", "| relationship | from → to | count | properties |", "|---|---|---|---|"]
        before = {(r["t"], r["a"], r["b"]) for r in seeded["rels"]} if seeded is not None else set()
        for r in m["rels"]:
            p = ", ".join(f"`{x}`" for x in m["rprops"][r["t"]])
            out.append(f"| `{r['t']}`{mark((r['t'], r['a'], r['b']) not in before)} | `{r['a']}` → `{r['b']}` | {r['n']:,} | {p} |")
        out.append("")
    return "\n".join(out)


def build() -> str:
    if not db.GRAPH_PREFIX.startswith(("schema", "faultlinetest")):
        raise SystemExit("set FAULTLINE_GRAPH_PREFIX=schema_ so the demo graphs are left alone")
    models = {}
    for t in TENANTS:
        seed.build(t, force=True)
        models[t] = read(Graph(t))
        if t == "kestrel":
            seeded = models[t]
            _agents_run(t)
            models[t] = {**read(Graph(t)), "seeded": seeded}
    for name in client().list_graphs():
        if name.startswith(db.GRAPH_PREFIX) and db.GRAPH_PREFIX.startswith("schema"):
            client().connection.execute_command("GRAPH.DELETE", name)
    return render(models)


if __name__ == "__main__":
    text = build()
    DOC.write_text(text + "\n")
    print(f"wrote {DOC.relative_to(DOC.parents[1])}: {text.count(chr(10)) + 1} lines")
    sys.exit(0)
